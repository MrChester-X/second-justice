import { DEMO_CASES_BY_ID } from "@/lib/api/analysis";

/**
 * Адрес рабочей области анализа.
 *
 * Сайт выложен статически, поэтому заранее собраны только страницы
 * демонстрационных дел — их идентификаторы известны на сборке. Дело,
 * загруженное пользователем, получает идентификатор в браузере, страницы
 * для него не существует, и оно открывается через общий маршрут с
 * параметром запроса.
 */
export function caseHref(id: string): string {
  return id in DEMO_CASES_BY_ID
    ? `/analysis/${id}/`
    : `/analysis/case/?id=${encodeURIComponent(id)}`;
}
